"""Renders src/font_clock.c: big Montserrat digits for the clock page, as an LVGL 8 font.

Only "-./0123456789:" so it stays small. Montserrat (SIL Open Font License) comes with LVGL.
    python3 tools/make_clock_font.py [path/to/Montserrat-Medium.ttf]
"""
import glob
import os
import sys

from PIL import ImageFont

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SIZE, BPP, FIRST, LAST = 112, 4, 0x2D, 0x3A
NAME = "font_clock"

ttf = sys.argv[1] if len(sys.argv) > 1 else (glob.glob(
    os.path.join(HERE, ".pio", "libdeps", "*", "lvgl", "scripts", "built_in_font", "Montserrat-Medium.ttf")) or [None])[0]
if not ttf:
    sys.exit("Montserrat-Medium.ttf not found: build once (pio run) or pass its path")
font = ImageFont.truetype(ttf, SIZE)
ascent, descent = font.getmetrics()

bitmap, glyphs = [], [(0, 0, 0, 0, 0, 0)]
for code in range(FIRST, LAST + 1):
    ch = chr(code)
    left, top, right, bottom = font.getbbox(ch)
    w, h = right - left, bottom - top
    mask = font.getmask(ch, mode="L")
    mw, mh = mask.size
    # Pack 4-bit alpha, rows back to back (LVGL's uncompressed format), high nibble first
    nibbles = []
    for y in range(h):
        for x in range(w):
            v = mask.getpixel((x, y)) if x < mw and y < mh else 0
            nibbles.append(v >> 4)
    if len(nibbles) % 2:
        nibbles.append(0)
    start = len(bitmap)
    bitmap += [(nibbles[i] << 4) | nibbles[i + 1] for i in range(0, len(nibbles), 2)]
    adv = round(font.getlength(ch) * 16)
    glyphs.append((start, adv, w, h, left, ascent - bottom))

out = [f"// Generated by tools/make_clock_font.py from Montserrat Medium (SIL OFL), {SIZE} px, {BPP} bpp.",
       "// Glyphs: - . / 0-9 :", "#include <lvgl.h>", "",
       "static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {"]
for i in range(0, len(bitmap), 24):
    out.append("    " + ", ".join(f"0x{b:02x}" for b in bitmap[i:i + 24]) + ",")
out += ["};", "", "static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {"]
for start, adv, w, h, ox, oy in glyphs:
    out.append(f"    {{.bitmap_index = {start}, .adv_w = {adv}, .box_w = {w}, .box_h = {h}, .ofs_x = {ox}, .ofs_y = {oy}}},")
out += ["};", "",
        "static const lv_font_fmt_txt_cmap_t cmaps[] = {",
        f"    {{.range_start = {FIRST}, .range_length = {LAST - FIRST + 1}, .glyph_id_start = 1, .unicode_list = NULL,",
        "     .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},",
        "};", "",
        "static lv_font_fmt_txt_glyph_cache_t cache;",
        "static const lv_font_fmt_txt_dsc_t font_dsc = {",
        "    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps, .kern_dsc = NULL, .kern_scale = 0,",
        f"    .cmap_num = 1, .bpp = {BPP}, .kern_classes = 0, .bitmap_format = 0, .cache = &cache,",
        "};", "",
        f"const lv_font_t {NAME} = {{",
        "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
        f"    .line_height = {ascent + descent}, .base_line = {descent}, .subpx = LV_FONT_SUBPX_NONE,",
        "    .underline_position = 0, .underline_thickness = 0, .dsc = &font_dsc,",
        "};", ""]
path = os.path.join(HERE, "src", f"{NAME}.c")
with open(path, "w") as f:
    f.write("\n".join(out))
print("wrote", os.path.relpath(path, HERE), f"({len(bitmap)} bytes of glyphs)")
